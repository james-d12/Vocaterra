using System.Collections.Concurrent;
using Vocaterra.Game.Core.Voxel;
using Vocaterra.Game.Core.World;
using Vocaterra.Game.Core.World.Streaming;
using Vocaterra.Game.Diagnostics;

namespace Vocaterra.Game.Streaming;

/// <summary>What the residency has done, for the run's report and the tests (counts never enter a compared output).</summary>
/// <param name="Resident">The chunks resident now.</param>
/// <param name="PlannedColumns">The columns the plan wants.</param>
/// <param name="InFlight">The columns whose chunks a worker is making.</param>
/// <param name="Installed">The chunks installed so far (a chunk a read generated is not counted).</param>
/// <param name="Evicted">The chunks dropped so far.</param>
/// <param name="Dropped">The generated columns thrown away because the player had moved on.</param>
/// <param name="Plans">How many plans were made.</param>
/// <param name="GenerateMilliseconds">The time the columns took to make, summed over every thread.</param>
public readonly record struct ResidencyStats(int Resident, int PlannedColumns, int InFlight, long Installed, long Evicted, long Dropped, long Plans, double GenerateMilliseconds);

/// <summary>
/// The residency driver of the streamed world (B07, biomes plan section 3.7), run by the game loop: it keeps resident the chunks <see cref="BandStreamer"/> wants round the player (the surface band of
/// each column, padded by one chunk each way, and everything under the near zone), generates the missing ones nearest first, and drops the unchanged ones the plan no longer holds. A column is made as one
/// piece (<see cref="StreamedWorld.GenerateLayers"/>), on a worker thread of the shared <see cref="JobPool"/> when it has any (the workers touch the pure source only, never the grid) and
/// inline within a per-frame budget when it has none; the game loop installs what comes back. Installing and dropping are not edits, a changed chunk is never dropped, and a chunk that was generated by
/// a read is simply resident already (a duplicate is dropped), so what is resident never changes a result.
/// </summary>
public sealed class ChunkResidency
{
    private const int MaxSubmitsPerFrame = 48;
    private const int MaxInFlight = 16;
    private const int MaxEvictionsPerFrame = 400;
    /// <summary>How many columns round the player's own must be resident before the simulation runs (see <see cref="IsNearReady"/>).</summary>
    public const int NearReadyRadius = 2;

    private const int RescanFrames = 20;
    private const int PartialPlanFrames = 12;
    private const long NearPlanRadiusSquared = 6 * 6;
    private const int JumpColumns = 8; // a plan for a place farther than this many columns from the last one is a jump
    private const long JumpPriorityStep = 1_000_000;

    private readonly VoxelGrid _grid;
    private readonly StreamedWorld _world;
    private readonly ColumnScratchPool _scratch; // B40: the window arrays of the columns the workers make, reused
    private BandStreamer _streamer;
    private readonly ColumnBandCache _bands;
    private readonly JobPool _pool;
    private readonly IPlaceInfo? _places;
    private int _maxResident;
    private readonly ConcurrentQueue<ColumnPackage> _done = new();
    private readonly HashSet<long> _inFlight = [];
    private readonly ConcurrentDictionary<long, byte> _bandJobs = new();
    private (int Dx, int Dz)[] _reach;
    private volatile BandPlan? _planNow; // read by the workers' staleness checks
    private VoxelChunkCoord _planFor;
    private int _epoch; // counts the jumps (a new plan for a place far from the last): the jobs of an older epoch queue behind every job of the newer one (B07b), do nothing when a worker reaches them, and their packages are told apart (B21)
    private int _flying; // the column jobs submitted whose packages the game loop has not taken yet, of every epoch (a jump forgets its columns in _inFlight, not these)
    private long _scannedAt = -1; // the grid's residency version when the last pass over the plan's columns found nothing to ask for
    private bool _needRescan;
    private double _started; // the clock at the start of the Update in progress, and its budget: what Over reads (a method, so a frame makes no closure)
    private double? _budget;
    private bool _planUnderground;
    private bool _planDue = true;
    private int _cursor;
    private List<VoxelChunkCoord> _evictions = [];
    private int _evictCursor;
    private int _frames;
    private int _partialFrame;
    private long _installed;
    private long _evicted;
    private long _dropped;
    private long _plans;
    private long _generateMicroseconds;
    private long _columnsGenerated;

    /// <summary>Creates the driver of a streamed grid.</summary>
    /// <param name="grid">The streamed grid; only the game loop's thread touches it.</param>
    /// <param name="world">The pure parts of the world.</param>
    /// <param name="policy">The radii.</param>
    /// <param name="pool">The workers (shared with the far view); with none the driver generates inline.</param>
    /// <param name="places">The place query, to know when the player is underground; <see langword="null"/> for never.</param>
    /// <param name="maxResident">The most chunks to keep resident: once the grid holds this many nothing new is asked for (after the chunks the plan let go have been dropped, so the old place never holds the cap against the new one).</param>
    /// <param name="bands">The band cache, shared with whatever else asks for bands; a new one when <see langword="null"/>.</param>
    public ChunkResidency(VoxelGrid grid, StreamedWorld world, BandStreamPolicy policy, JobPool pool, IPlaceInfo? places = null, int maxResident = int.MaxValue, ColumnBandCache? bands = null)
    {
        ArgumentNullException.ThrowIfNull(grid);
        ArgumentNullException.ThrowIfNull(world);
        ArgumentNullException.ThrowIfNull(pool);
        if (!grid.IsStreamed)
        {
            throw new ArgumentException("The residency driver serves a streamed grid.", nameof(grid));
        }

        _grid = grid;
        _world = world;
        _scratch = new ColumnScratchPool(world.CreateScratch);
        _streamer = new BandStreamer(policy, grid.Limits);
        _bands = bands ?? new ColumnBandCache(world.Bands);
        _pool = pool;
        _places = places;
        _maxResident = maxResident;
        _reach = Disc(_streamer.BandReach);
    }

    /// <summary>
    /// Takes other radii and another cap while the driver goes on (a quality change, B21): what the workers are making stays valid (a chunk is a function of its coordinates, the plan in force keeps filtering what is installed) and the next
    /// plan, made at once from the radii, asks for and drops what the new radii hold, so a change loses no package, makes no column twice and leaves no chunk half installed (a package is installed whole).
    /// </summary>
    /// <param name="policy">The radii.</param>
    /// <param name="maxResident">The most chunks to keep resident.</param>
    public void Reconfigure(BandStreamPolicy policy, int maxResident)
    {
        _streamer = new BandStreamer(policy, _grid.Limits);
        _reach = Disc(_streamer.BandReach);
        _maxResident = maxResident;
        _planDue = true;
        (_cursor, _evictions, _evictCursor) = (0, [], 0); // the old plan's list of what to drop is not the new radii's; the plan in force stays until the new one is made, so what arrives meanwhile is installed by it
        _needRescan = true;
    }

    /// <summary>The radii in force.</summary>
    public BandStreamPolicy Policy => _streamer.Policy;

    /// <summary>The band cache.</summary>
    public ColumnBandCache Bands => _bands;

    /// <summary>The plan in force, or <see langword="null"/> before the first one is made.</summary>
    public BandPlan? Plan => _planNow;

    /// <summary>Whether everything the plan wants is resident, nothing is being made (no column job is left with a worker or in the queue, of the old place too) and nothing is left to drop: what a scripted run waits for before a picture.</summary>
    public bool IsSettled => _planNow is { } plan && !_planDue && _inFlight.Count == 0 && _flying == 0 && _done.IsEmpty && _cursor >= plan.Columns.Count && _evictCursor >= _evictions.Count;

    /// <summary>
    /// Whether the chunks under and round a place are resident: the plan is for the chunk column the place is in and every column within <see cref="NearReadyRadius"/> of it holds what the plan wants of it. The game
    /// holds the simulation while this is false (a start, a jump), so the body never stands on, or reads, a world the residency has not made, and no frame has to generate it on the game loop's thread.
    /// </summary>
    /// <param name="x">The place's x in blocks.</param>
    /// <param name="y">The place's y.</param>
    /// <param name="z">The place's z.</param>
    public bool IsNearReady(float x, float y, float z)
    {
        var plan = _planNow;
        var chunk = VoxelChunkCoord.FromBlock((int)MathF.Floor(x), (int)MathF.Floor(y), (int)MathF.Floor(z));
        if (plan is null || plan.Player.X != chunk.X || plan.Player.Z != chunk.Z)
        {
            return false;
        }

        for (var dz = -NearReadyRadius; dz <= NearReadyRadius; dz++)
        {
            for (var dx = -NearReadyRadius; dx <= NearReadyRadius; dx++)
            {
                if (plan.TryGetLayers(chunk.X + dx, chunk.Z + dz, out var min, out var max) && !AllResident(new WantedColumn(chunk.X + dx, chunk.Z + dz, min, max)))
                {
                    return false;
                }
            }
        }

        return true;
    }

    /// <summary>How many column jobs were handed to the workers and whose packages the game loop has not taken yet, of every epoch (after a jump the old place's are still counted until they come back).</summary>
    public int Flying => _flying;

    /// <summary>How many columns were made, on a worker or inline, over every plan: a column made for a place the player had left, or made twice, shows here (the tests compare it with the columns resident).</summary>
    public long ColumnsGenerated => Interlocked.Read(ref _columnsGenerated);

    /// <summary>What the driver has done.</summary>
    public ResidencyStats Stats => new(_grid.ResidentChunkCount, _planNow?.Columns.Count ?? 0, _inFlight.Count, _installed, _evicted, _dropped, _plans, Interlocked.Read(ref _generateMicroseconds) / 1000.0);

    /// <summary>
    /// One frame's work, from the player's eye: plans when the player's chunk (or whether they are underground) changed, installs what the workers finished, asks for the missing columns nearest first and drops
    /// what the plan let go. Never reads a block through the grid.
    /// </summary>
    /// <param name="eyeX">The eye's x.</param>
    /// <param name="eyeY">The eye's y.</param>
    /// <param name="eyeZ">The eye's z.</param>
    /// <param name="budgetMilliseconds">The most time to spend on the game loop's thread, or <see langword="null"/> for as much as it takes (the settle step).</param>
    public void Update(float eyeX, float eyeY, float eyeZ, double? budgetMilliseconds)
    {
        _started = MonotonicClock.Milliseconds();
        _budget = budgetMilliseconds;
        _frames++;
        var feet = VoxelChunkCoord.FromBlock((int)MathF.Floor(eyeX), (int)MathF.Floor(eyeY), (int)MathF.Floor(eyeZ));
        var underground = _places?.IsUnderground((int)MathF.Floor(eyeX), (int)MathF.Floor(eyeY), (int)MathF.Floor(eyeZ)) ?? false;
        if (_planNow is null || feet != _planFor || underground != _planUnderground)
        {
            if (_planNow is not null && Math.Max(Math.Abs(feet.X - _planFor.X), Math.Abs(feet.Z - _planFor.Z)) > JumpColumns)
            {
                _epoch++; // a jump, not a walk: what was asked for at the old place goes behind what the new place needs, and no longer holds a request slot
                _inFlight.Clear();
                (_planNow, _cursor, _evictions, _evictCursor) = (null, 0, [], 0); // the old place's plan asks for nothing more
            }

            (_planFor, _planUnderground, _planDue) = (feet, underground, true);
        }

        if (_planDue)
        {
            TryPlan();
        }

        Install();
        if (_planNow is { } plan)
        {
            Evict(plan); // before the asks: the room a drop makes is used in the same frame, and the cap never waits on chunks the plan no longer holds
            Request(plan);
        }
    }

    // Whether the frame's budget is spent (the Update in progress's).
    private bool Over() => _budget is { } budget && MonotonicClock.Milliseconds() - _started >= budget;

    /// <summary>
    /// Brings the world round the eye fully up to date before the call returns (the settle step of a scripted run, and a teleport): plans, makes and installs every wanted column, waiting for the workers, and
    /// drops what the plan let go.
    /// </summary>
    /// <param name="eyeX">The eye's x.</param>
    /// <param name="eyeY">The eye's y.</param>
    /// <param name="eyeZ">The eye's z.</param>
    /// <param name="timeoutMilliseconds">The longest to wait for the workers.</param>
    /// <returns>Whether the world settled before the timeout.</returns>
    public bool Settle(float eyeX, float eyeY, float eyeZ, double timeoutMilliseconds = 120_000)
    {
        var started = MonotonicClock.Milliseconds();
        while (true)
        {
            Update(eyeX, eyeY, eyeZ, null);
            if (IsSettled)
            {
                return true;
            }

            if (MonotonicClock.Milliseconds() - started > timeoutMilliseconds)
            {
                return false;
            }

            if (_pool.Workers == 0)
            {
                _ = _pool.RunInline(null);
            }
            else
            {
                Thread.Sleep(1);
            }
        }
    }

    /// <summary>
    /// Makes the world round a place now, up to the point <see cref="IsNearReady"/> says the body may stand there: plans for the place and installs its nearest columns, waiting for the workers, and returns
    /// at once when that is done or after the time limit. The rest of the plan is left to the frames (B07b: a far move makes its near zone the way a start does).
    /// </summary>
    /// <param name="x">The place's x in blocks.</param>
    /// <param name="y">The place's y.</param>
    /// <param name="z">The place's z.</param>
    /// <param name="timeoutMilliseconds">The longest to wait.</param>
    /// <returns>Whether the near zone is ready.</returns>
    public bool SettleNear(float x, float y, float z, double timeoutMilliseconds)
    {
        var started = MonotonicClock.Milliseconds();
        while (true)
        {
            Update(x, y, z, 6);
            if (IsNearReady(x, y, z))
            {
                return true;
            }

            if (MonotonicClock.Milliseconds() - started > timeoutMilliseconds)
            {
                return false;
            }

            if (_pool.Workers == 0)
            {
                _ = _pool.RunInline(null);
            }
            else
            {
                Thread.Sleep(1);
            }
        }
    }

    // Makes the plan. The bands nearest the player are asked for first; once the near ones are known a plan is made at once, from the bands known so far (a column whose band is not known yet is not
    // wanted yet), and made again every few frames while the rest arrive, so the world round the player starts to fill in a moment after a start or a jump and not after every band in the disc
    // is made. Only a plan made with every band known lets chunks go.
    private void TryPlan()
    {
        var pending = false;
        var nearPending = false;
        var limits = _grid.Limits;
        foreach (var (dx, dz) in _reach)
        {
            var cx = _planFor.X + dx;
            var cz = _planFor.Z + dz;
            if (cx < limits.MinChunkX || cx >= limits.EndChunkX || cz < limits.MinChunkZ || cz >= limits.EndChunkZ || _bands.TryGet(cx, cz, out _))
            {
                continue;
            }

            if (_pool.Workers == 0)
            {
                if (Over())
                {
                    pending = true;
                    nearPending |= (dx * dx) + (dz * dz) <= NearPlanRadiusSquared;
                    break; // the rest of the bands are made on the next frames
                }

                _ = _bands.Get(cx, cz);
                continue;
            }

            pending = true;
            nearPending |= (dx * dx) + (dz * dz) <= NearPlanRadiusSquared;
            // B39: one job a group of 4 x 4 columns, at the distance of its nearest column that is wanted (the loop goes nearest first): it shapes the group's window once and makes every band of the group from it, and keeps the window for
            // the columns' layers. Each column's layers are still a job of their own, so the nearest column never waits for the others'.
            var key = ColumnGroupCache.KeyOf(cx, cz);
            if (_bandJobs.TryAdd(key, 0))
            {
                var distance = PriorityOf(((long)dx * dx) + ((long)dz * dz));
                var epoch = _epoch;
                _pool.Submit(JobLane.Residency, distance, () => StaleBand(epoch, key), () =>
                {
                    _ = _bands.GetThroughGroup(cx, cz);
                    _ = _bandJobs.TryRemove(key, out _);
                });
            }
        }

        if (nearPending || (pending && _planNow is not null && _frames - _partialFrame < PartialPlanFrames && _planNow.Player == _planFor && _planNow.Underground == _planUnderground))
        {
            return;
        }

        var plan = _streamer.Plan(_planFor, _planUnderground, (x, z) => _bands.TryGet(x, z, out var band) ? band : ColumnBand.Empty);
        _planNow = plan;
        _cursor = 0;
        _plans++;
        if (pending)
        {
            _partialFrame = _frames; // a partial plan: asked again in a few frames, and nothing is dropped by it
            _evictions = [];
            _evictCursor = 0;
            return;
        }

        _planDue = false;
        _evictions = [.. BandStreamer.Evictable(plan, GridResidency.Resident(_grid))];
        _evictCursor = 0;
    }

    // Installs the columns the workers finished that the plan still wants. A package of an older epoch (a column asked for at the place before a jump) is used for what the plan wants of it (a chunk is a function of its
    // coordinates, so what an old job made is right for the new place too) but never frees a request slot: the jump cleared them and the key may now stand for a request of the new place.
    private void Install()
    {
        var plan = _planNow;
        var installs = 0;
        while (_done.TryDequeue(out var package))
        {
            _flying--;
            if (package.Epoch == _epoch)
            {
                _ = _inFlight.Remove(ColumnBandCache.KeyOf(package.ChunkX, package.ChunkZ));
            }

            if (plan is not null && plan.TryGetLayers(package.ChunkX, package.ChunkZ, out var min, out var max))
            {
                foreach (var chunk in package.Layers)
                {
                    if (chunk.Coord.Y >= min && chunk.Coord.Y <= max && GridResidency.Install(_grid, chunk))
                    {
                        _installed++;
                        installs++;
                    }
                }
            }
            else
            {
                _dropped++;
                _needRescan = true; // the plan may come back to the column
            }

            if (installs >= 96 || Over())
            {
                return;
            }
        }
    }

    // Asks for the missing columns of the plan, nearest first.
    private void Request(BandPlan plan)
    {
        var columns = plan.Columns;
        if (_cursor >= columns.Count)
        {
            // A column whose package was dropped, or whose chunks were evicted by a read's side effects, is asked for again: a pass over the plan every few frames, and only when something could have changed (B21).
            if (_inFlight.Count == 0 && _frames % RescanFrames == 0 && (_needRescan || _scannedAt != _grid.ResidencyVersion))
            {
                _cursor = 0;
                _needRescan = false;
                _scannedAt = _grid.ResidencyVersion;
            }
            else
            {
                return;
            }
        }

        var submitted = 0;
        while (_cursor < columns.Count)
        {
            if (_pool.Workers == 0 ? Over() : submitted >= MaxSubmitsPerFrame || _inFlight.Count >= MaxInFlight)
            {
                break;
            }

            if (_grid.ResidentChunkCount >= _maxResident)
            {
                if (_evictCursor < _evictions.Count)
                {
                    break; // B24 (review C8): what the plan let go is still to be dropped, and it is what holds the cap (the old place after a walk or a jump): wait for the room, keeping the place in the plan
                }

                _cursor = columns.Count; // the cap: nothing new is asked for; a cap too low only leaves the far land to the far view
                break;
            }

            var column = columns[_cursor];
            if (AllResident(column))
            {
                _cursor++;
                continue;
            }

            var key = ColumnBandCache.KeyOf(column.ChunkX, column.ChunkZ);
            if (_inFlight.Contains(key))
            {
                _cursor++;
                continue;
            }

            if (_pool.Workers == 0)
            {
                var layers = Generate(column.ChunkX, column.ChunkZ, column.MinLayer, column.MaxLayer);
                foreach (var chunk in layers)
                {
                    if (GridResidency.Install(_grid, chunk))
                    {
                        _installed++;
                    }
                }

                _cursor++;
                continue;
            }

            _ = _inFlight.Add(key);
            _flying++;
            var distance = PriorityOf(((long)(column.ChunkX - _planFor.X) * (column.ChunkX - _planFor.X)) + ((long)(column.ChunkZ - _planFor.Z) * (column.ChunkZ - _planFor.Z)));
            var (cx, cz, lo, hi, epoch) = (column.ChunkX, column.ChunkZ, column.MinLayer, column.MaxLayer, _epoch);
            // A column the player has moved away from by the time a worker reaches it (the plan no longer holds it, or a jump made the request old) is not made, but its package still comes back (empty), so the game loop
            // forgets that it asked.
            _pool.Submit(
                JobLane.Residency,
                distance,
                static () => false,
                () => _done.Enqueue(new ColumnPackage(cx, cz, epoch, epoch != Volatile.Read(ref _epoch) || _planNow is not { } current || !current.TryGetLayers(cx, cz, out _, out _) ? [] : Generate(cx, cz, lo, hi))));
            submitted++;
            _cursor++;
        }
    }

    // A job's place in the queue: its squared distance from the player, less a step for every jump since, so the newest place's jobs all go first.
    private long PriorityOf(long distanceSquared) => distanceSquared - ((long)_epoch * JumpPriorityStep);

    // A band job of an older epoch is skipped by the worker that reaches it, and its key is freed so the band is asked for again if the place is near again.
    private bool StaleBand(int epoch, long key)
    {
        if (epoch == Volatile.Read(ref _epoch))
        {
            return false;
        }

        _ = _bandJobs.TryRemove(key, out _);
        return true;
    }

    private IReadOnlyList<ChunkData> Generate(int chunkX, int chunkZ, int minLayer, int maxLayer)
    {
        var started = MonotonicClock.Milliseconds();
        _ = Interlocked.Increment(ref _columnsGenerated);
        _ = _bands.Groups.TryGet(chunkX, chunkZ, out var group); // the window its band was made from (B39), when it is still held; else the column's own
        var scratch = _scratch.Rent();
        IReadOnlyList<ChunkData> layers;
        try
        {
            layers = _world.GenerateLayers(chunkX, chunkZ, minLayer, maxLayer, group, scratch);
        }
        finally
        {
            _scratch.Return(scratch);
        }

        _ = Interlocked.Add(ref _generateMicroseconds, (long)((MonotonicClock.Milliseconds() - started) * 1000));
        return layers;
    }

    private bool AllResident(WantedColumn column)
    {
        for (var layer = column.MinLayer; layer <= column.MaxLayer; layer++)
        {
            if (!_grid.IsResident(new VoxelChunkCoord(column.ChunkX, layer, column.ChunkZ)))
            {
                return false;
            }
        }

        return true;
    }

    // Drops what the plan no longer holds, a bounded number a frame; a chunk that changed stays (the grid refuses it).
    private void Evict(BandPlan plan)
    {
        var dropped = 0;
        while (_evictCursor < _evictions.Count && dropped < MaxEvictionsPerFrame && !Over())
        {
            var chunk = _evictions[_evictCursor++];
            if (!plan.Holds(chunk) && GridResidency.TryEvict(_grid, chunk))
            {
                _evicted++;
                dropped++;
            }
        }
    }

    // The columns of a disc round (0, 0), nearest first.
    private static (int Dx, int Dz)[] Disc(int radius)
    {
        var list = new List<(long Distance, int Dx, int Dz)>();
        for (var dz = -radius; dz <= radius; dz++)
        {
            for (var dx = -radius; dx <= radius; dx++)
            {
                var distance = ((long)dx * dx) + ((long)dz * dz);
                if (distance <= (long)radius * radius)
                {
                    list.Add((distance, dx, dz));
                }
            }
        }

        list.Sort(static (a, b) => a.Distance != b.Distance ? a.Distance.CompareTo(b.Distance) : a.Dz != b.Dz ? a.Dz.CompareTo(b.Dz) : a.Dx.CompareTo(b.Dx));
        return [.. list.Select(static t => (t.Dx, t.Dz))];
    }

    private sealed record ColumnPackage(int ChunkX, int ChunkZ, int Epoch, IReadOnlyList<ChunkData> Layers);
}
